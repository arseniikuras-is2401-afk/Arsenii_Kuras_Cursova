function snippet(file, signature, maxLines, skipDoc = false) {
  const lines = read(file).split("\n");
  const start = lines.findIndex((line) => line.includes(signature));
  if (start < 0) {
    throw new Error(`Не знайдено «${signature}» у ${file}`);
  }
  const indent = lines[start].match(/^\s*/)[0].length;
  const result = [lines[start]];
  let inDoc = false;
  for (let i = start + 1; i < lines.length; i += 1) {
    const line = lines[i];
    if (line.trim() && line.match(/^\s*/)[0].length <= indent &&
        !line.trim().startsWith(")")) {
      break;
    }
    if (skipDoc) {
      const quotes = (line.match(/"""/g) || []).length;
      if (quotes === 1) {
        inDoc = !inDoc;
        continue;
      }
      if (inDoc || quotes === 2) {
        continue;
      }
    }
    result.push(line);
  }
  while (result.length && !result[result.length - 1].trim()) {
    result.pop();
  }
  const shown = result.slice(0, maxLines).map((line) => line.slice(indent));
  if (result.length > maxLines) {
    shown.push("    ...");
  }
  return shown.filter((line, i, all) => !(line === "" && all[i - 1] === ""));
}

