async function build() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const body = documentOf([...introduction(), ...section1(), ...section2(),
    ...section3(), ...section4(), ...conclusions()]);
  const bodyFigures = N.counters.figures;
  fs.writeFileSync(path.join(OUT_DIR, "body.docx"),
    await Packer.toBuffer(body));
  const appendix = documentOf(appendixA(),
    { top: 1134, bottom: 1134, left: 1418, right: 567 });
  fs.writeFileSync(path.join(OUT_DIR, "appendix_a.docx"),
    await Packer.toBuffer(appendix));
  for (const old of ["appendix_b.docx", "appendix_c.docx"]) {
    fs.rmSync(path.join(OUT_DIR, old), { force: true });
  }
  const stats = { figures: bodyFigures, sources: 13, appendices: 1 };
  fs.writeFileSync(path.join(OUT_DIR, "stats.json"),
    JSON.stringify(stats, null, 2));
  console.log("OK", JSON.stringify(stats));
}

